"""T-C1: the web client's generated API types equal the API's current OpenAPI schema.

`web/src/api/openapi.json` and `web/src/api/generated.ts` are generated by `make api-types`
(tools/codegen/openapi_ts.py). This test fails when either is missing or stale (the API changed and nobody
regenerated), and checks that generation is byte-stable. Fix a failure with `make api-types`.
"""

from __future__ import annotations

import subprocess
import sys

from conftest import REPO_ROOT

GEN = REPO_ROOT / "tools" / "codegen" / "openapi_ts.py"


def run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(GEN), *args], cwd=REPO_ROOT, capture_output=True, text=True)


def test_committed_generated_files_are_current():
    r = run("--check")
    assert r.returncode == 0, r.stdout + r.stderr + "\nrun `make api-types` and commit the result"


def test_generation_is_byte_stable(tmp_path):
    a, b = tmp_path / "a", tmp_path / "b"
    assert run("--out-dir", str(a)).returncode == 0
    assert run("--out-dir", str(b)).returncode == 0
    for name in ("openapi.json", "generated.ts"):
        assert (a / name).read_bytes() == (b / name).read_bytes()


def test_check_detects_a_stale_file(tmp_path):
    assert run("--out-dir", str(tmp_path)).returncode == 0
    (tmp_path / "generated.ts").write_text("// stale\n")
    r = run("--check", "--out-dir", str(tmp_path))
    assert r.returncode == 1 and "generated.ts" in r.stdout


def test_check_detects_a_missing_file(tmp_path):
    r = run("--check", "--out-dir", str(tmp_path))
    assert r.returncode == 1 and "missing" in r.stdout


def test_generated_types_cover_request_bodies():
    text = (REPO_ROOT / "web/src/api/generated.ts").read_text()
    for name in ("CreateDraft", "RejectDraft", "PostReply", "PostEvent", "DevLogin"):
        assert f"export interface {name} " in text
