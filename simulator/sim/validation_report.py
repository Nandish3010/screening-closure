def _pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def _yn(b):
    return "yes" if b else "no"


def _target(result: dict, tid: str) -> dict:
    return next(t for t in result["cohort_targets"] if t["id"] == tid)


def _primary(t: dict) -> dict:
    return next(v for v in t["variants"] if v["name"] == t["primary_variant"])


def _row(v: dict, metric: str) -> dict:
    return next(r for r in v["rows"] if r["metric"] == metric)


def _managed_gap(result: dict) -> tuple[float, float]:
    """Smallest and largest shortfall (points, simulated below observed) over the held-out managed-programme completion rows:
    Kaiser (Corley 2017) at 30 and 60 days, Scotland and England at 12 months."""
    picks = [(_primary(_target(result, "corley-kaiser")), "completion@30"), (_primary(_target(result, "corley-kaiser")), "completion@60"),
             (_primary(_target(result, "phs-scotland")), "completion@360"), (_primary(_target(result, "nhs-england-bcsp")), "completion@360")]
    gaps = []
    for v, m in picks:
        r = _row(v, m)
        assert not r["in_sample"], m
        gaps.append(-r["diff_points"])
    return min(gaps), max(gaps)


def _rows_table(v: dict) -> list[str]:
    out = ["| Metric | Observed | Simulated mean | 95% replication interval | Difference | Within tolerance | Observed inside the replication interval | Simulated mean inside the observed 95% CI | Row type |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in v["rows"]:
        if r["kind"] == "time":
            o, s, lo, hi = f"{r['observed']:.0f} d", f"{r['sim_mean']:.1f} d", f"{r['sim_lo']:.1f} to {r['sim_hi']:.1f} d", f"ratio {r['ratio']:.2f}"
        else:
            o, s, lo, hi = _pct(r["observed"]), _pct(r["sim_mean"]), f"{_pct(r['sim_lo'])} to {_pct(r['sim_hi'])}", f"{r['diff_points']:+.1f} points"
        wi = _yn(r.get("sim_inside_obs_interval")) if "sim_inside_obs_interval" in r else "n/a"
        out.append(f"| {r['metric']} | {o} | {s} | {lo} | {hi} | **{_yn(r['within_tolerance'])}** | {_yn(r['covered_by_replication_interval'])} | {wi} | {'in-sample (flagged, not scored)' if r['in_sample'] else 'held out'} |")
    return out


