#!/usr/bin/env python3
"""Turn the secrets in Secret Manager into the env files the hosted demo runs on (docs/governance/hosting-gcp.md).

Pure functions (`build_files`) so a unit test can check, without a cloud, that what we render passes the API's fail-closed
production check (app.auth.secure_config_problems). The command line reads a JSON object of secrets on stdin and writes the files
(mode 0600) into --out-dir. Nothing here prints a secret.

Two modes of the SAME stack:
  production  APP_ENV=production, OIDC sign-in, wall clock. This is what judges reach.
  seed        APP_ENV=dev, dev login, simulation clock. Used once, with the public edge STOPPED and every port on loopback,
              to load the synthetic cohort and take the snapshot (deploy/gcp/seed.sh). Never reachable from the internet.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

# Secrets that must exist in Secret Manager (names without the sc-demo- prefix). generated by deploy/gcp/deploy.sh.
TOKEN_SECRETS = ("dev-auth-secret", "scheduler-token", "watchdog-token", "automation-token", "agency-token", "metrics-token")
DB_SECRETS = ("postgres-password", "app-db-password", "keycloak-db-password", "keycloak-admin-password")
USER_SECRETS = ("pw-coordinator", "pw-clinician", "pw-supervisor", "pw-patient", "pw-lab", "pw-owner", "pw-specialist")
REQUIRED = TOKEN_SECRETS + DB_SECRETS + USER_SECRETS

REALM = "screening-closure"


def _lines(d: dict[str, str]) -> str:
    for k, v in d.items():
        if "\n" in str(v):
            raise ValueError(f"{k}: newline in value")
    return "".join(f"{k}={v}\n" for k, v in d.items())


def build_files(host: str, secrets: dict[str, str], mode: str = "production", demo_patient_ref: str = "") -> dict[str, dict[str, str]]:
    missing = [n for n in REQUIRED if not secrets.get(n)]
    if missing:
        raise ValueError("missing secrets: " + ", ".join(missing))
    if mode not in ("production", "seed"):
        raise ValueError("mode must be production or seed")
    prod = mode == "production"
    issuer = f"https://{host}/auth/realms/{REALM}"
    s = secrets

    # docker compose interpolation (--env-file): the values docker-compose.yml reads as ${VAR:-default}.
    compose = {
        "POSTGRES_PASSWORD": s["postgres-password"],
        "APP_DB_PASSWORD": s["app-db-password"],
        "AUTH_MODE": "oidc" if prod else "dev",
        "OIDC_ISSUER": issuer,
        "OIDC_JWKS_URL": f"http://keycloak:8080/auth/realms/{REALM}/protocol/openid-connect/certs",
        "CLOCK_MODE": "wall" if prod else "sim",
        "OUTREACH_DEMO_APPROVAL": "0",  # never the demo placeholder: the policy stays unsigned and the automation sends nothing
        "LLM_PROVIDER": "anthropic",
        "LLM_CACHE_MODE": "replay",  # recorded Claude outputs only
        "LLM_NETWORK_ENABLED": "false",
        "LLM_DAILY_TOKEN_BUDGET": "0",  # and a zero spend cap even if someone flips the switches
        "TRIAGE_REMOTE_URL": "",  # no host model server in the cloud: see hosting-gcp.md, "Reply triage"
        "REQUIRE_LEADER_FENCE": "false",
        "KC_DB_PASSWORD": s["keycloak-db-password"],
        "KEYCLOAK_ADMIN_PASSWORD": s["keycloak-admin-password"],
        "KC_PW_COORDINATOR": s["pw-coordinator"],
        "KC_PW_CLINICIAN": s["pw-clinician"],
        "KC_PW_SUPERVISOR": s["pw-supervisor"],
        "KC_PW_PATIENT": s["pw-patient"],
        "KC_PW_LAB": s["pw-lab"],
        "KC_PW_OWNER": s["pw-owner"],
        "KC_PW_SPECIALIST": s["pw-specialist"],
        "DEMO_PATIENT_REF": demo_patient_ref or "Patient/demo-patient",
        "SC_PUBLIC_HOST": host,
        "FHIR_HEAP_MB": "1536" if prod else "3072",  # the seed loads 20 MB bundles; serving needs far less
    }
    if not prod:
        compose["SIM_CLOCK_START"] = os.environ.get("SIM_CLOCK_START", "")
    api = {
        "APP_ENV": "production" if prod else "dev",
        "DEV_LOGIN_ENABLED": "false" if prod else "true",
        "DEV_AUTH_SECRET": s["dev-auth-secret"],
        "SCHEDULER_SERVICE_TOKEN": s["scheduler-token"],
        "WATCHDOG_SERVICE_TOKEN": s["watchdog-token"],
        "AUTOMATION_SERVICE_TOKEN": s["automation-token"],
        "AGENCY_SERVICE_TOKEN": s["agency-token"],
        "METRICS_SCRAPE_TOKEN": s["metrics-token"],
        "MAX_INFLIGHT_REQUESTS": "40",
        "CORS_ALLOW_ORIGINS": f"https://{host}",
        "LOG_FORMAT": "json",
    }
    if not prod and os.environ.get("SIM_CLOCK_START"):
        api["SIM_CLOCK_START"] = os.environ["SIM_CLOCK_START"]
    return {
        "compose.env": compose,
        "api.env": api,
        "scheduler.env": {"SCHEDULER_SERVICE_TOKEN": s["scheduler-token"]},
        "watchdog.env": {"WATCHDOG_SERVICE_TOKEN": s["watchdog-token"]},
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", required=True)
    ap.add_argument("--mode", default="production")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--demo-patient-ref", default="")
    a = ap.parse_args()
    files = build_files(a.host, json.load(sys.stdin), a.mode, a.demo_patient_ref)
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for name, values in files.items():
        p = out / name
        fd = os.open(p, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as fh:
            fh.write(_lines(values))
    print(f"rendered {len(files)} env files for mode={a.mode} into {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
