#!/usr/bin/env python3
"""Dump the API's OpenAPI schema and generate TypeScript types from it (C1, T-C1).

Writes two files, byte-stable across runs (sorted keys, no timestamps, no hosts, no DB or secrets needed):

  web/src/api/openapi.json   the schema `app.openapi()` returns for the FastAPI app
  web/src/api/generated.ts   one interface per components.schemas entry, plus `Routes` (every route with its path/query
                             parameters, request body and 2xx response type) and `ROUTES` (the list of "METHOD /path")

`web/src/api/contract.ts` stays the hand-written contract of what the UI sends and expects; the type-level test
web/tests/contract.generated.test.ts ties the two together. When the API changes, run `make api-types` and commit.

Usage: python tools/codegen/openapi_ts.py [--check] [--out-dir DIR]
  (no flag)  write the files        --check  compare, print a diff summary and exit 1 on drift
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / "web" / "src" / "api"
BANNER = "// GENERATED by tools/codegen/openapi_ts.py from the API's OpenAPI schema. Do not edit; run `make api-types`.\n"
METHODS = ("get", "post", "put", "patch", "delete")


def build_schema() -> dict:
    for p in (ROOT / "api", ROOT):
        if str(p) not in sys.path:
            sys.path.insert(0, str(p))
    os.environ.setdefault("LOG_FORMAT", "text")
    from app.main import app  # importing builds the app; the lifespan (DB, secrets) only runs when a server starts

    return json.loads(json.dumps(app.openapi(), sort_keys=True))


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return ref_name(s["$ref"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "const" in s:
        return json.dumps(s["const"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            parts = []
            for p in s[key]:
                t = ts_type(p)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    if "allOf" in s:
        return " & ".join(ts_type(p) for p in s["allOf"])
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}) for x in t)
    if t in ("integer", "number"):
        return "number"
    if t == "string":
        return "string"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        item = ts_type(s.get("items", {}))
        return f"({item})[]" if "|" in item or "&" in item else f"{item}[]"
    if t == "object" or "properties" in s or "additionalProperties" in s:
        return object_type(s)
    return "unknown"


def object_type(s: dict) -> str:
    props = s.get("properties", {})
    ap = s.get("additionalProperties")
    if not props:
        if isinstance(ap, dict) and ap:
            return f"Record<string, {ts_type(ap)}>"
        return "Record<string, unknown>"
    req = set(s.get("required", []))
    lines = [f"{json.dumps(k)}{'' if k in req else '?'}: {ts_type(v)};" for k, v in sorted(props.items())]
    if ap is True or (isinstance(ap, dict) and ap):
        lines.append(f"[key: string]: {'unknown' if ap is True else ts_type(ap)};")
    return "{ " + " ".join(lines) + " }"


def interface(name: str, s: dict) -> str:
    out = []
    if s.get("description"):
        out.append("/** " + " ".join(s["description"].split()).replace("*/", "* /") + " */")
    if (s.get("type") == "object" or "properties" in s) and "anyOf" not in s and "allOf" not in s:
        props, req, ap = s.get("properties", {}), set(s.get("required", [])), s.get("additionalProperties")
        out.append(f"export interface {name} {{")
        for k, v in sorted(props.items()):
            out.append(f"  {json.dumps(k)}{'' if k in req else '?'}: {ts_type(v)};")
        if ap is True or (isinstance(ap, dict) and ap):
            out.append(f"  [key: string]: {'unknown' if ap is True else ts_type(ap)};")
        out.append("}")
    else:
        out.append(f"export type {name} = {ts_type(s)};")
    return "\n".join(out)


def route_entry(op: dict) -> str:
    params = op.get("parameters", [])
    parts = []
    for loc in ("path", "query"):
        ps = sorted((p for p in params if p["in"] == loc), key=lambda p: p["name"])
        if ps:
            body = " ".join(f"{json.dumps(p['name'])}{'' if p.get('required') else '?'}: {ts_type(p.get('schema', {}))};" for p in ps)
            parts.append(f"{loc}: {{ {body} }};")
    rb = op.get("requestBody")
    if rb:
        js = rb.get("content", {}).get("application/json", {}).get("schema")
        parts.append(f"body{'' if rb.get('required') else '?'}: {ts_type(js) if js is not None else 'unknown'};")
    resp = "unknown"
    for code in sorted(op.get("responses", {})):
        if code.startswith("2"):
            js = op["responses"][code].get("content", {}).get("application/json", {}).get("schema")
            resp = ts_type(js) if js is not None else "unknown"
            break
    parts.append(f"response: {resp};")
    return "{ " + " ".join(parts) + " }"


def generate_ts(schema: dict) -> str:
    out = [BANNER, f"// API: {schema['info']['title']} {schema['info']['version']} (OpenAPI {schema['openapi']})\n"]
    for name, s in sorted(schema.get("components", {}).get("schemas", {}).items()):
        out.append(interface(name, s) + "\n")
    routes, keys = [], []
    for path, item in sorted(schema["paths"].items()):
        for m in METHODS:
            if m in item:
                key = f"{m.upper()} {path}"
                keys.append(key)
                routes.append(f"  {json.dumps(key)}: {route_entry(item[m])};")
    out.append("/** Every route: path and query parameters, request body and 2xx response (most responses are untyped objects). */")
    out.append("export interface Routes {\n" + "\n".join(routes) + "\n}\n")
    out.append("export type RouteKey = keyof Routes;")
    out.append("export const ROUTES: readonly RouteKey[] = [\n" + "\n".join(f"  {json.dumps(k)}," for k in keys) + "\n];")
    return "\n".join(out) + "\n"


def render(schema: dict) -> dict[str, str]:
    return {"openapi.json": json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n", "generated.ts": generate_ts(schema)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    files = render(build_schema())
    if not args.check:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (args.out_dir / name).write_text(text, encoding="utf-8")
            print(f"wrote {args.out_dir / name}")
        return 0
    bad = 0
    for name, text in files.items():
        p = args.out_dir / name
        if not p.exists():
            print(f"{p}: missing")
            bad += 1
            continue
        cur = p.read_text(encoding="utf-8")
        if cur != text:
            bad += 1
            diff = list(difflib.unified_diff(cur.splitlines(), text.splitlines(), f"{name} (committed)", f"{name} (from the API now)", lineterm="", n=0))
            print(f"{p}: out of date ({len(diff)} diff lines)")
            print("\n".join(diff[:30]))
    if bad:
        print("API types are out of date: run `make api-types` and commit the result.")
        return 1
    print("API types are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
