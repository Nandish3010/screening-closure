def _load_before() -> dict | None:
    try:
        return json.loads(BEFORE_PATH.read_text())
    except (OSError, ValueError):
        return None


def _before_after(result: dict) -> list[str]:
    before = _load_before()
    if before is None:
        return []
    bt = {t["id"]: t for t in before["cohort_targets"]}
    out = ["## Before and after the timing mixture (B21)", "",
           "Primary variant of every target, every row. *Before* is the B20 run (main at db1d13d: one booking lead, 24-day median, for every case); "
           "*after* is this run. The row type is the current one: three Scottish rows became in-sample in B21 because the fast lane is calibrated to them.", "",
           "| Target | Row | Observed | Before: simulated | Before: within | After: simulated | After: within | Row type now |",
           "|---|---|---|---|---|---|---|---|"]
    for t in result["cohort_targets"]:
        idx = next(i for i, v in enumerate(t["variants"]) if v["name"] == t["primary_variant"])
        v = t["variants"][idx]
        b = bt.get(t["id"])
        brows = {r["metric"]: r for r in b["variants"][idx]["rows"]} if b else {}
        for r in v["rows"]:
            br = brows.get(r["metric"])

            def fmt(x, time=r["kind"] == "time"):
                return f"{x:.0f} d" if time else _pct(x)

            bs = fmt(br["sim_mean"]) if br else "n/a"
            bw = _yn(br["within_tolerance"]) if br else "n/a"
            out.append(f"| {t['title']} | {r['metric']} | {fmt(r['observed'])} | {bs} | {bw} | {fmt(r['sim_mean'])} | **{_yn(r['within_tolerance'])}** | "
                       f"{'in-sample' if r['in_sample'] else 'held out'} |")
    out += ["", "| Target | Verdict before | Verdict after |", "|---|---|---|"]
    for t in result["cohort_targets"]:
        b = bt.get(t["id"])
        out.append(f"| {t['title']} | {b['verdict'] if b else 'n/a'} | **{t['verdict']}** |")
    bt_tr = {x["id"]: x for x in before["effect_trials"]}
    out += ["", "| Trial | Simulated ratio before | Verdict before | Simulated ratio after | Verdict after |", "|---|---|---|---|---|"]
    for tr in result["effect_trials"]:
        b = bt_tr.get(tr["id"])
        bs, bv = (f"{b['sim_ratio']:.2f}", b["verdict"]) if b else ("n/a", "n/a")
        out.append(f"| {tr['title']} | {bs} | {bv} | {tr['sim_ratio']:.2f} | **{tr['verdict']}** |")
    out.append("")
    return out


def claim_status(result: dict, rows: tuple) -> tuple[str, list[dict]]:
    """B21: 'passes' only if every row testing the claim is held out and within tolerance."""
    found = []
    for tid, vi, metric in rows:
        t = _target(result, tid)
        found.append(_row(t["variants"][vi], metric) | {"target": t["title"]})
    if any(r["in_sample"] for r in found):
        return "excluded: in-sample calibration rows, so it cannot pass (not validated)", found
    if all(r["within_tolerance"] for r in found):
        return "passes: may be quoted, with the validation row", found
    return "fails: withdrawn", found


def _claims(result: dict) -> list[str]:
    out = ["## Which timing claims may be quoted (B21)", "",
           "A timing statement may be quoted only if every row that tests it is held out and within tolerance; a claim tested by an in-sample row (one the calibration was fitted to, such as the Scottish 4- and 8-week shares) is excluded and can never pass. Generated from the verdicts above.", "",
           "| Claim | Tested by | Simulated against observed | Status |", "|---|---|---|---|"]
    for claim, rows in TIMING_CLAIMS:
        status, found = claim_status(result, rows)
        tested = "; ".join(f"{r['target']}, {r['metric']}" for r in found)
        vals = "; ".join((f"{r['sim_mean']:.0f} d vs {r['observed']:.0f} d" if r["kind"] == "time" else f"{_pct(r['sim_mean'])} vs {_pct(r['observed'])}")
                         for r in found)
        out.append(f"| {claim} | {tested} | {vals} | **{status}** |")
    out.append("")
    return out
