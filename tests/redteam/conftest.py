"""Red-team harness: makes api/ importable, records every case and writes results.json / results.md (D14)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
for p in (REPO / "api", REPO / "api" / "tests", HERE):  # api/tests: fixtures and helpers phase B reuses
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from harness import CATEGORIES, Case, Recorder, show  # noqa: E402

_RESULTS: dict[str, dict] = {}
ORDER = list(CATEGORIES.values())


@pytest.fixture
def rt(request):
    rec = Recorder(request.node.user_properties)
    return rec


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    case = getattr(getattr(item, "callspec", None), "params", {}).get("case")
    if not isinstance(case, Case):
        return
    if rep.when == "call" or (rep.when == "setup" and rep.outcome != "passed"):
        actual = next((v for k, v in item.user_properties if k == "rt_actual"), "(no outcome recorded)")
        reason = str(getattr(rep, "wasxfail", "") or "")
        if hasattr(rep, "wasxfail"):  # xfail (strict) honoured: the test failed as marked
            if rep.outcome == "skipped":
                status = "known-limitation" if reason.startswith("known limitation") else "exposed"
            else:  # strict xpass is reported as a failure by pytest
                status = "fail"
        else:
            status = "pass" if rep.outcome == "passed" else "fail"
        if rep.outcome == "failed" and "XPASS(strict)" in str(rep.longrepr):
            status = "fail"
        _RESULTS[case.id] = {
            "id": case.id, "category": case.category, "abuse_case": case.abuse, "input": case.shown,
            "expected": case.expected, "actual": actual, "status": status, "reason": reason,
        }


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def pytest_sessionfinish(session, exitstatus):
    opt = session.config.option
    if not _RESULTS or opt.keyword or opt.markexpr or opt.collectonly:
        return  # a partial run must not rewrite the committed files
    rows = sorted(_RESULTS.values(), key=lambda r: (ORDER.index(r["category"]), _natural(r["id"])))
    summary: dict[str, dict] = {}
    for r in rows:
        s = summary.setdefault(r["category"], {"cases": 0, "pass": 0, "known-limitation": 0, "exposed": 0, "fail": 0})
        s["cases"] += 1
        s[r["status"]] += 1
    (HERE / "results.json").write_text(
        json.dumps({"summary": summary, "cases": rows}, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8")
    lines = ["# Red-team results", "",
             "Generated by `make test-redteam` (`tests/redteam/conftest.py`); do not edit. See docs/governance/red-team.md.", "",
             "| Category | Cases | Pass | Known limitation | Exposed | Fail |", "|---|---|---|---|---|---|"]
    for cat in ORDER:
        if cat in summary:
            s = summary[cat]
            lines.append(f"| {cat} | {s['cases']} | {s['pass']} | {s['known-limitation']} | {s['exposed']} | {s['fail']} |")
    lines += ["", "| ID | Category | Input | Expected | Actual | Status |", "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['id']} | {r['category']} | {_cell(r['input'])} | {_cell(r['expected'])} | {_cell(r['actual'])} | {r['status']} |")
    (HERE / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _natural(case_id: str):
    import re
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", case_id)]
