#!/usr/bin/env python3
"""Generate the test-count table of docs/submission/evaluation-summary.md, so the numbers cannot go stale by hand.

    python tools/check/evaluation_counts.py            rewrite the marked block in evaluation-summary.md   (make evaluation-counts)
    python tools/check/evaluation_counts.py --check    exit 1 if the block differs from a fresh count      (make evaluation-counts-check)
    python tools/check/evaluation_counts.py --print    print the table, change nothing

The method is COLLECTION, not execution: for every suite the tool runs the same test selection as the make target of that
suite, but only lists the tests (`pytest --collect-only`, `playwright test --list`; vitest cannot list parameterised tests, so its count is the total of a run). The count is therefore
"tests that the suite selects", reproducible on any checkout in well under a minute, and it is labelled "collected" in the
table. It is NOT a pass count: whether the suites pass is what `make check-full` and the CI jobs say. A collected count
includes tests that skip themselves when a service is down and tests marked xfail; the table says so.

The block sits between the markers below; the text around it is hand-written. The model-check row has no test count (it is
an exhaustive search, not a list of tests); its state counts live in docs/governance/verification.md. The security row's
"combinations probed" figure is read from docs/governance/rbac-matrix.md, which `make test-security` already keeps equal to a
fresh render.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs/submission/evaluation-summary.md"
RBAC = ROOT / "docs/governance/rbac-matrix.md"
START = "<!-- evaluation-counts:start (generated by tools/check/evaluation_counts.py; edit nothing between the markers) -->"
END = "<!-- evaluation-counts:end -->"

PY = str(ROOT / ".venv/bin/python") if (ROOT / ".venv/bin/python").exists() else sys.executable

# name, what it is, make target, pytest arguments (the same as the target's, plus the PYTHONPATH it uses)
PYTEST_SUITES = [
    ("test", "API, engine, simulator, tools and repository checks (the `test` stage)", "make test",
     ["api/tests", "simulator/tests", "-m", "not integration and not chaos and not oidc"], "api:simulator"),
    ("test-db", "API against a real Postgres (integration; each skips itself if Postgres is down)", "make test-db",
     ["api/tests", "-m", "integration and not chaos"], "api:simulator"),
    ("test-security", "Security and RBAC matrix (pytest part)", "make test-security",
     ["tests/test_rbac_matrix.py", "tests/test_phi_scan.py", "tests/test_compose_lint.py"], "api"),
    ("test-tools", "Tools (demo, video, pilot cost model, AI-safety, reviews, calibration, repository checks)", "make test-tools",
     ["tests", "--ignore=tests/redteam", "tools/demo/tests", "tools/video/tests", "tools/pilot/tests", "tools/rai/tests",
      "-m", "not live"], "api"),
    ("test-redteam", "Red team (abuse, injection, authorisation; includes known-limitation xfails)", "make test-redteam",
     ["tests/redteam"], "api"),
]
WEB_SUITES = [
    ("web-test", "Web unit and component (vitest)", "make web-test"),
    ("web-e2e", "Web browser (Playwright, including the accessibility audit)", "make web-e2e"),
]


def _run(cmd: list[str], cwd: Path, env_extra: dict[str, str] | None = None) -> str:
    env = {**os.environ, **(env_extra or {})}
    p = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True)
    if p.returncode not in (0, 5):  # 5 = pytest "no tests collected"
        raise SystemExit(f"evaluation_counts: `{' '.join(cmd)}` failed ({p.returncode}):\n{(p.stdout + p.stderr)[-1500:]}")
    return p.stdout


def count_pytest(args: list[str], pythonpath: str) -> int:
    out = _run([PY, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider", *args], ROOT,
               {"PYTHONPATH": ":".join(str(ROOT / p) for p in pythonpath.split(":"))})
    m = re.search(r"^(?:(\d+)/\d+|(\d+)) tests? collected", out, re.M)
    if not m:
        raise SystemExit(f"evaluation_counts: no 'N tests collected' line from pytest for {args}:\n{out[-800:]}")
    return int(m.group(1) or m.group(2))


def _web_ready() -> None:
    if not (ROOT / "web/node_modules").exists():
        raise SystemExit("evaluation_counts: web/node_modules is missing; run `make web-install` first")


def count_vitest() -> int:
    """`vitest list` does not expand parameterised tests (611 listed against 649 run), so the only exact count is a run's
    own total (`numTotalTests`: passed, failed and skipped alike). About 15 s; it is the one suite counted by running."""
    import tempfile

    with tempfile.TemporaryDirectory() as d:
        out_file = Path(d) / "vitest.json"
        # the exit status is ignored on purpose: a failing test is still a counted test, and `make web-test` is what gates it
        subprocess.run(["npx", "--no-install", "vitest", "run", "--reporter=json", f"--outputFile={out_file}"], cwd=ROOT / "web",
                       capture_output=True, text=True)
        if not out_file.exists():
            raise SystemExit("evaluation_counts: vitest wrote no JSON report")
        return int(json.loads(out_file.read_text())["numTotalTests"])


def count_playwright() -> int:
    out = _run(["npx", "--no-install", "playwright", "test", "--list"], ROOT / "web")
    m = re.search(r"^Total: (\d+) tests?", out, re.M)
    if not m:
        raise SystemExit(f"evaluation_counts: no 'Total: N tests' line from playwright:\n{out[-800:]}")
    return int(m.group(1))


def rbac_probed() -> int:
    m = re.search(r"^- (\d+) role, route and scope combinations probed", RBAC.read_text(encoding="utf-8"), re.M)
    if not m:
        raise SystemExit(f"evaluation_counts: the probe count line is missing from {RBAC.relative_to(ROOT)}")
    return int(m.group(1))


def collect() -> dict[str, int]:
    _web_ready()
    jobs = {name: (lambda a=a, pp=pp: count_pytest(a, pp)) for name, _d, _m, a, pp in PYTEST_SUITES}
    jobs["web-test"] = count_vitest
    jobs["web-e2e"] = count_playwright
    with ThreadPoolExecutor(max_workers=4) as pool:
        futs = {k: pool.submit(fn) for k, fn in jobs.items()}
        return {k: f.result() for k, f in futs.items()}


def render(counts: dict[str, int]) -> str:
    rows = [
        "| Suite | Tests collected | How to run |",
        "|---|---|---|",
    ]

    def row(desc: str, cell: str, how: str) -> None:
        rows.append(f"| {desc} | {cell} | {how} |")

    row(*[PYTEST_SUITES[0][1], f"{counts['test']:,}", f"`{PYTEST_SUITES[0][2]}`"])
    row(PYTEST_SUITES[1][1], f"{counts['test-db']:,}", f"`{PYTEST_SUITES[1][2]}`")
    row("Model check of the state machine (exhaustive search, not a list of tests; state counts in [verification.md](../governance/verification.md))",
        "n/a", "`make verify` (full), `make verify-quick` (a labelled slice)")
    row(PYTEST_SUITES[2][1] + f"; the RBAC matrix probes {rbac_probed():,} role, route and scope combinations",
        f"{counts['test-security']:,}", f"`{PYTEST_SUITES[2][2]}`")
    row(PYTEST_SUITES[3][1], f"{counts['test-tools']:,}", f"`{PYTEST_SUITES[3][2]}`")
    row(PYTEST_SUITES[4][1], f"{counts['test-redteam']:,}", f"`{PYTEST_SUITES[4][2]}`")
    row(WEB_SUITES[0][1] + " (counted by running the suite: vitest cannot list parameterised tests)", f"{counts['web-test']:,}", f"`{WEB_SUITES[0][2]}`")
    row(WEB_SUITES[1][1], f"{counts['web-e2e']:,}", f"`{WEB_SUITES[1][2]}`")
    row("Chaos (stops and restarts containers) and identity provider (real Keycloak)", "not counted; not part of `check-full`",
        "`make test-chaos`, `make test-oidc`")
    row("Documented test cases, each with a pass criterion", "see [../../project/TEST-CASES.md](../../project/TEST-CASES.md)", "")
    return "\n".join(rows)


def block(counts: dict[str, int]) -> str:
    return f"{START}\n{render(counts)}\n{END}"


def splice(text: str, new_block: str) -> str:
    if START not in text or END not in text:
        raise SystemExit(f"evaluation_counts: the markers are missing from {DOC.relative_to(ROOT)}")
    head, rest = text.split(START, 1)
    _old, tail = rest.split(END, 1)
    return head + new_block + tail


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="exit 1 if the block in evaluation-summary.md is out of date")
    g.add_argument("--print", action="store_true", help="print the table and change nothing")
    args = ap.parse_args(argv)
    counts = collect()
    fresh = block(counts)
    if args.print:
        print(fresh)
        return 0
    text = DOC.read_text(encoding="utf-8")
    new_text = splice(text, fresh)
    if args.check:
        if new_text != text:
            print("evaluation-counts-check: the test-count block in docs/submission/evaluation-summary.md is out of date; "
                  "run `make evaluation-counts` and commit the result.\nfresh counts: " + ", ".join(f"{k}={v}" for k, v in counts.items()))
            return 1
        print("evaluation-counts-check: ok (" + ", ".join(f"{k}={v}" for k, v in counts.items()) + ")")
        return 0
    DOC.write_text(new_text, encoding="utf-8")
    print("evaluation-counts: wrote " + ", ".join(f"{k}={v}" for k, v in counts.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
