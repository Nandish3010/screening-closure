#!/usr/bin/env python3
"""Seed a throwaway Postgres database with open cases for the sweep load test (F6, T-F8).

* Creates (or recreates) the database `closure_load` on the compose Postgres published on
  localhost:5433, applies the engine's own migrations (`api/migrations/*.sql`, through
  `app.db.run_migrations`), then bulk-inserts `--size` open cases with realistic event logs.
* Never touches the dev database: the target name is fixed to `closure_load*` and the script
  refuses anything else (the admin connection only issues CREATE/DROP DATABASE for that name).
* Direct SQL (`COPY`) for speed. Every log is generated by the engine's own state machine, so it
  replays cleanly: the script replays each case it writes and fails loudly otherwise.

Cases are spread over the pathway's open states (main chain plus the consent_withdrawn,
referral_rejected and lost_contact side states). Where a case sits relative to its SLA is drawn
from a fixed mixture, and in the default `daily` scenario the previous sweep (one working day
before `SWEEP_NOW`) has already run, so only breaches and rungs that became due since then are
left for the timed sweep. The `backlog` scenario skips that earlier sweep: every breach and rung
is still pending (a cold start after an outage). The expected event count the timed sweep must
emit is computed here with the pure planner and stored in the returned stats.

    python tools/load/seed_cases.py --size 10000 [--scenario daily|backlog] [--seed 20261017]

The script never drops the database it fills; tools/load/time_sweep.py owns the lifecycle
(drop at the end unless KEEP_LOAD_DB=1).

Environment: LOAD_PG_ADMIN_URL (default postgresql://closure:closure_dev_password@localhost:5433/postgres).
"""

from __future__ import annotations

import argparse
import os
import random
import sys
import time
import uuid
from collections import Counter
from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "api"))

import psycopg  # noqa: E402
from psycopg import sql  # noqa: E402
from psycopg.types.json import Jsonb  # noqa: E402

from app.calendar import WorkingCalendar, load_calendar  # noqa: E402
from app.db import create_pool, run_migrations  # noqa: E402
from app.events import CASE_CREATED, Event  # noqa: E402
from app.pathway import Pathway, load_pathway  # noqa: E402
from app.state_machine import replay_model  # noqa: E402
from app.sweep import plan_case  # noqa: E402

LOAD_DB = "closure_load"
DEFAULT_ADMIN_URL = "postgresql://closure:closure_dev_password@localhost:5433/postgres"
DEFAULT_SEED = 20261017
# A Tuesday. The previous sweep ran one working day earlier (Monday), at the same time of day.
SWEEP_NOW = datetime(2026, 3, 10, 8, 0, tzinfo=UTC)
PREV_SWEEP = SWEEP_NOW - timedelta(days=1)

# Where the open cases sit. Weights sum to 1.
STATE_WEIGHTS = {
    "result_received": 0.14, "acknowledged": 0.12, "owner_accepted": 0.13, "patient_contacted": 0.14,
    "patient_acknowledged": 0.11, "confirmatory_booked": 0.12, "confirmatory_completed": 0.08,
    "clinician_reviewed": 0.04, "consent_withdrawn": 0.04, "referral_rejected": 0.04, "lost_contact": 0.04,
}
# For states that have an SLA: where the due date falls relative to the sweep. (weight, kind)
PHASES = [(0.58, "healthy"), (0.03, "newly_due"), (0.20, "overdue_recent"), (0.19, "overdue_old")]
ACTOR_BY_EVENT = {
    "acknowledge": "primary_care_owner:pco-1", "accept_ownership": "primary_care_owner:pco-1",
    "contact_patient": "primary_care_owner:pco-1", "patient_acknowledge": "patient:p",
    "book_confirmatory": "specialist_owner:so-1", "complete_confirmatory": "specialist_owner:so-1",
    "clinician_review": "specialist_owner:so-1",
}


@dataclass
class SeedStats:
    size: int
    scenario: str
    seed: int
    cases: int = 0
    events: int = 0
    by_state: Counter = field(default_factory=Counter)
    pre_swept_events: int = 0
    expected_mark_overdue: int = 0
    expected_escalate: int = 0
    seconds: float = 0.0

    @property
    def expected_emitted(self) -> int:
        return self.expected_mark_overdue + self.expected_escalate


def _swap_db(url: str, name: str) -> str:
    parts = urlsplit(url)
    return urlunsplit(parts._replace(path="/" + name))


def admin_url() -> str:
    return os.environ.get("LOAD_PG_ADMIN_URL", DEFAULT_ADMIN_URL)


def load_url() -> str:
    return _swap_db(admin_url(), LOAD_DB)


def assert_throwaway(name: str) -> None:
    if not name.startswith("closure_load"):
        raise SystemExit(f"refusing to touch database {name!r}: load tests use closure_load only")


def pg_reachable(url: str | None = None, timeout: float = 2.0) -> bool:
    try:
        with psycopg.connect(url or admin_url(), connect_timeout=int(max(1, timeout))):
            return True
    except psycopg.Error:
        return False


def recreate_database(name: str = LOAD_DB) -> None:
    assert_throwaway(name)
    with psycopg.connect(admin_url(), autocommit=True) as conn:
        conn.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name)))
        conn.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))


def drop_database(name: str = LOAD_DB) -> None:
    assert_throwaway(name)
    with psycopg.connect(admin_url(), autocommit=True) as conn:
        conn.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name)))


def load_engine() -> tuple[Pathway, WorkingCalendar]:
    pathway = load_pathway(os.environ.get("PATHWAY_PATH", REPO_ROOT / "config/pathways/colorectal_fit.yaml"))
    calendar = load_calendar(os.environ.get("CALENDAR_PATH", REPO_ROOT / "config/calendar.yaml"))
    return pathway, calendar


def _pick(rng: random.Random, weighted):
    r, acc = rng.random(), 0.0
    for item, w in weighted:
        acc += w
        if r < acc:
            return item
    return weighted[-1][0]


def _uuid(rng: random.Random) -> uuid.UUID:
    return uuid.UUID(int=rng.getrandbits(128), version=4)


def _enter_time_for_due(calendar: WorkingCalendar, sla_days: int, target_due: datetime) -> datetime:
    """A state-entry instant whose SLA expires (approximately) at `target_due`."""
    enter = target_due - timedelta(days=sla_days * 7 / 5)
    for _ in range(3):  # add_working_days is monotone and piecewise linear: converges fast
        due = calendar.add_working_days(enter, sla_days)
        enter += target_due - due
    return enter


def _final_state_enter_time(rng, calendar, pathway, state: str, phase: str) -> datetime:
    sla = pathway.sla_for_state(state)
    if sla is None:
        return SWEEP_NOW - timedelta(days=rng.uniform(0.5, 60))
    days = sla[1]
    if phase == "healthy":
        target_due = SWEEP_NOW + timedelta(days=rng.uniform(0.2, 20))
    elif phase == "newly_due":
        target_due = SWEEP_NOW - timedelta(days=rng.uniform(0.02, 0.98))
    elif phase == "overdue_recent":
        target_due = PREV_SWEEP - timedelta(days=rng.uniform(0.0, 4.0))
    else:
        target_due = PREV_SWEEP - timedelta(days=rng.uniform(4.0, 25.0))
    return _enter_time_for_due(calendar, days, target_due)


def _chain_to(pathway: Pathway, state: str) -> list[tuple[str, str, dict, str]]:
    """Events (type, from_state, payload, actor) that lead from the initial state to `state`."""
    chain = []
    for t in pathway.main_transitions:
        if t.to_state == pathway.terminal_state:
            break
        if t.event == "book_confirmatory":
            # The referral precedes the booking (A18): it meets the 15-working-day referral milestone and starts the
            # 31-working-day colonoscopy milestone, as in a real case. Without it every old case would breach the
            # referral milestone.
            chain.append(("handoff_requested", t.from_state, {"to_provider": "provider-a"}, "primary_care_owner:pco-1"))
            chain.append(("handoff_accepted", t.from_state, {}, "specialist_owner:so-1"))
        chain.append((t.event, t.from_state, {}, ACTOR_BY_EVENT.get(t.event, "primary_care_owner:pco-1")))
        if t.to_state == state:
            return chain
    raise ValueError(f"state {state!r} is not on the main chain")


def build_case_events(rng, pathway, calendar, case_id: uuid.UUID | None = None) -> tuple[uuid.UUID, list[Event]]:
    """One case's event log up to the drawn state, without any scheduler events."""
    case_id = case_id or _uuid(rng)
    state = _pick(rng, list(STATE_WEIGHTS.items()))
    phase = _pick(rng, [(k, w) for w, k in PHASES])
    side = state in pathway.side_states
    if side:
        steps: list[tuple[str, str, dict, str]]
        if state == "consent_withdrawn":
            base = rng.choice(["owner_accepted", "patient_contacted", "patient_acknowledged", "confirmatory_booked"])
            steps = _chain_to(pathway, base) + [("consent_updated", base, {"withdrawn": True}, "patient:p")]
        elif state == "referral_rejected":
            base = rng.choice(["patient_acknowledged", "confirmatory_booked"])
            steps = _chain_to(pathway, base) + [
                ("handoff_requested", base, {"to_provider": "provider-b"}, "primary_care_owner:pco-1"),
                ("handoff_rejected", base, {"reason": "capacity"}, "specialist_owner:so-1")]
        else:  # lost_contact
            steps = _chain_to(pathway, "patient_contacted") + [
                ("mark_lost_contact", "patient_contacted", {"failed_attempts": 3}, "coordinator:c-1")]
        enter = _final_state_enter_time(rng, calendar, pathway, state, phase)
    else:
        steps = [] if state == pathway.initial_state else _chain_to(pathway, state)
        enter = _final_state_enter_time(rng, calendar, pathway, state, phase)

    # Walk backwards from the final entry time so earlier steps precede it.
    times = [enter]
    for _ in range(max(len(steps) - 1, 0)):
        times.append(times[-1] - timedelta(days=rng.uniform(0.3, 2.0)))
    times.reverse()
    if steps:
        created = times[0] - timedelta(days=rng.uniform(0.2, 1.5))
    else:
        created = enter  # still in the initial state: the SLA clock starts at case_created
    events = [Event(case_id, CASE_CREATED, created, "system:intake", {}, _uuid(rng))]
    for (etype, _frm, payload, actor), at in zip(steps, times):
        events.append(Event(case_id, etype, at, actor, dict(payload), _uuid(rng)))
    return case_id, events


def seed(
    size: int,
    *,
    scenario: str = "daily",
    seed_value: int = DEFAULT_SEED,
    recreate: bool = True,
    batch: int = 5000,
    log=print,
) -> SeedStats:
    """Create `closure_load`, migrate it and insert `size` open cases. Returns the stats."""
    if scenario not in {"daily", "backlog"}:
        raise ValueError("scenario must be 'daily' or 'backlog'")
    pathway, calendar = load_engine()
    t0 = time.perf_counter()
    if recreate:
        recreate_database()
    pool = create_pool(load_url(), max_size=4)
    try:
        run_migrations(pool)
    finally:
        pool.close()

    rng = random.Random(seed_value)
    stats = SeedStats(size=size, scenario=scenario, seed=seed_value)
    case_rows: list[tuple] = []
    event_rows: list[tuple] = []

    with psycopg.connect(load_url()) as conn:
        def flush():
            if not case_rows:
                return
            with conn.cursor() as cur:
                with cur.copy("COPY cases (id, pathway, current_state, created_at, updated_at) FROM STDIN") as cp:
                    for row in case_rows:
                        cp.write_row(row)
                with cur.copy("COPY events (event_id, case_id, seq, type, at, actor, payload) FROM STDIN") as cp:
                    for row in event_rows:
                        cp.write_row(row)
            conn.commit()
            case_rows.clear()
            event_rows.clear()

        for i in range(size):
            case_id, events = build_case_events(rng, pathway, calendar)
            model = replay_model(events, pathway)
            if scenario == "daily":
                for ev in plan_case(case_id, model, pathway, calendar, PREV_SWEEP):
                    # What the previous sweep would have appended (same ids, same order).
                    ev = Event(case_id, ev.type, PREV_SWEEP, ev.actor, ev.payload, ev.event_id)
                    events.append(ev)
                    stats.pre_swept_events += 1
                model = replay_model(events, pathway)  # raises if the planner's output is not valid
            for ev in plan_case(case_id, model, pathway, calendar, SWEEP_NOW):
                if ev.type == "mark_overdue":
                    stats.expected_mark_overdue += 1
                else:
                    stats.expected_escalate += 1
            case_rows.append((case_id, pathway.name, model.state, events[0].at, events[-1].at))
            for seq, ev in enumerate(events, start=1):
                event_rows.append((ev.event_id, case_id, seq, ev.type, ev.at, ev.actor, Jsonb(ev.payload)))
            stats.by_state[model.state] += 1
            stats.cases += 1
            stats.events += len(events)
            if len(case_rows) >= batch:
                flush()
        flush()
        conn.execute("ANALYZE cases")
        conn.execute("ANALYZE events")
        conn.commit()
    stats.seconds = time.perf_counter() - t0
    log(f"seeded {stats.cases} cases / {stats.events} events into {LOAD_DB} ({scenario}) in {stats.seconds:.1f}s; "
        f"the timed sweep should emit {stats.expected_emitted} events "
        f"({stats.expected_mark_overdue} mark_overdue + {stats.expected_escalate} escalate)")
    return stats


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--size", type=int, required=True, help="number of open cases (1000, 10000, 100000)")
    ap.add_argument("--scenario", choices=["daily", "backlog"], default="daily")
    ap.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = ap.parse_args(argv)
    if not pg_reachable():
        print(f"Postgres not reachable at {urlsplit(admin_url()).hostname}:{urlsplit(admin_url()).port}; "
              "start it with `docker compose up -d postgres`", file=sys.stderr)
        return 2
    stats = seed(args.size, scenario=args.scenario, seed_value=args.seed)
    for state, n in sorted(stats.by_state.items(), key=lambda kv: -kv[1]):
        print(f"  {state:24s} {n:7d}")
    print(f"database {LOAD_DB} left in place; drop it with: python tools/load/time_sweep.py --drop")
    return 0


if __name__ == "__main__":
    sys.exit(main())
