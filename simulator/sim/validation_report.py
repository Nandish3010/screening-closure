    a = out.append
    a("**What B21 changed.** The timing structure, not a fit to these targets: a fast lane (booked when the result is reviewed, the managed-programme wait, calibrated to the Scottish 4- and 8-week bands) and a slow lane (the old staff steps and a heavier-tailed wait), mixed by programme management. Before B21 almost nobody had a colonoscopy within 30 days in any arm or setting; that floor is gone.")
